"""Generate LaTeX tables for the paper from the frozen metric CSVs."""
from __future__ import annotations

import csv
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RESULTS = ROOT / "results"
PREDICTIONS = RESULTS / "predictions"

SHORT = {
    "jev": "JEV",
    "nli": "NLI-DeBERTa",
    "qwen-direct-compact": "Q-direct (compact)",
    "qwen-direct-expanded": "Q-direct (expanded)",
    "qwen-cot-compact": "Q-reason (compact)",
    "qwen-cot-expanded": "Q-reason (expanded)",
}
DATASET = {
    "fever": "FEVER",
    "scifact": "SciFact",
    "hover": "HoVer",
    "vitaminc": "VitaminC",
    "climate_fever": "Climate-FEVER",
}
ORDER = ["fever", "scifact", "hover", "vitaminc", "climate_fever"]


def num(value: str, digits: int = 3) -> str:
    if value in (None, "", "None"):
        return "--"
    return f"{float(value):.{digits}f}"


def main() -> None:
    summary = list(csv.DictReader((RESULTS / "summary.csv").open()))
    per_class = list(csv.DictReader((RESULTS / "per_class.csv").open()))
    failures = list(csv.DictReader((RESULTS / "failure_features.csv").open()))
    systems = list(dict.fromkeys(row["system"] for row in summary))
    datasets = [d for d in ORDER if any(row["dataset"] == d for row in summary)]

    lines = ["% Generated by eval/make_paper_tables.py. Do not edit by hand.", ""]

    lines.append("\\begin{table*}[t]\\centering\\small")
    lines.append("\\caption{Accuracy on the frozen evaluation sample "
                 "($n=300$ per dataset per system, 264 on SciFact; all systems see the same claims, the same label space "
                 "and evidence rendered under a single 6{,}000-character cap). Protocol failures are excluded from the "
                 "denominator; counting them as errors gives Q-reason (expanded) 0.517 on HoVer and a pooled 0.651.}")
    lines.append("\\label{tab:accuracy}")
    lines.append("\\begin{tabular}{l" + "r" * len(datasets) + "r}")
    lines.append("\\toprule")
    lines.append("System & " + " & ".join(DATASET[d] for d in datasets) + " & Mean \\\\")
    lines.append("\\midrule")
    for system in systems:
        cells, values = [], []
        for dataset in datasets:
            row = next((r for r in summary if r["system"] == system and r["dataset"] == dataset), None)
            if row is None or not row["n_scored"] or row["n_scored"] == "0":
                cells.append("--")
            else:
                cells.append(num(row["accuracy"]))
                values.append(float(row["accuracy"]))
        mean = f"{sum(values)/len(values):.3f}" if values else "--"
        lines.append(f"{SHORT.get(system, system)} & " + " & ".join(cells) + f" & {mean} \\\\")
    lines.append("\\bottomrule")
    lines.append("\\end{tabular}")
    lines.append("\\end{table*}")
    lines.append("")

    lines.append("\\begin{table}[t]\\centering\\small")
    lines.append("\\caption{Macro-F1 for all systems; Brier and ECE shown where a system returns a distribution. Brier is the standard "
                 "multiclass score (squared error summed over the dataset's label space, range $[0,2]$) and ECE is an "
                 "equal-frequency expected calibration error; a uniform predictor scores 0.50 on HoVer's binary space and "
                 "0.67 on the three-way datasets. The hosted Qwen endpoint returns no token log-probabilities, so no "
                 "calibrated distribution is measurable for its conditions under this protocol (n/a).}")
    lines.append("\\label{tab:macro}")
    lines.append("\\begin{tabular}{llrrr}")
    lines.append("\\toprule")
    lines.append("System & Dataset & Macro-F1 & Brier & ECE \\\\")
    lines.append("\\midrule")
    for system in systems:
        for dataset in datasets:
            row = next((r for r in summary if r["system"] == system and r["dataset"] == dataset), None)
            if row is None:
                continue
            brier = "n/a" if row["brier"] == "None" else num(row["brier"])
            ece = "n/a" if row["ece"] == "None" else num(row["ece"])
            lines.append(f"{SHORT.get(system, system)} & {DATASET[dataset]} & {num(row['macro_f1'])} & {brier} & {ece} \\\\")
        lines.append("\\addlinespace")
    lines.pop()
    lines.append("\\bottomrule")
    lines.append("\\end{tabular}")
    lines.append("\\end{table}")
    lines.append("")

    lines.append("\\begin{table}[t]\\centering\\small")
    lines.append("\\caption{Per-class F1 on the four hardest datasets, showing where each system loses. HoVer is binary, so it has no NEI column.}")
    lines.append("\\label{tab:perclass}")
    lines.append("\\begin{tabular}{llrrr}")
    lines.append("\\toprule")
    lines.append("Dataset & System & SUPPORTS & REFUTES & NEI \\\\")
    lines.append("\\midrule")
    for dataset in ("hover", "climate_fever", "scifact", "vitaminc"):
        for system in systems:
            cells = []
            for label in ("SUPPORTS", "REFUTES", "NEI"):
                row = next((r for r in per_class if r["system"] == system and r["dataset"] == dataset and r["label"] == label), None)
                cells.append(num(row["f1"]) if row and row["support"] != "0" else "--")
            lines.append(f"{DATASET[dataset]} & {SHORT.get(system, system)} & " + " & ".join(cells) + " \\\\")
        lines.append("\\addlinespace")
    lines.pop()
    lines.append("\\bottomrule")
    lines.append("\\end{tabular}")
    lines.append("\\end{table}")
    lines.append("")

    lines.append("\\begin{table}[t]\\centering\\small")
    lines.append("\\caption{Efficiency, protocol reliability and cost. Latency is pooled over all requests of a system and is "
                 "end-to-end request time including network and provider queueing, so it compares deployment paths rather "
                 "than pure model compute; requests that ended in provider errors are excluded. Cost is computed from logged token usage at list prices (\\sysjev{} "
                 "\\$0.042/M input tokens, output free; Qwen3.5-9B \\$0.10/M input, \\$0.15/M output on SiliconFlow); "
                 "the NLI baseline runs on local hardware so its marginal cost is electricity only.}")
    lines.append("\\label{tab:efficiency}")
    lines.append("\\begin{tabular}{lrrrrr}")
    lines.append("\\toprule")
    lines.append("System & Median (ms) & Mean (ms) & p95 (ms) & Output tokens & Cost/1k \\\\")
    lines.append("\\midrule")
    for system in systems:
        latencies, tokens_seen, cost = [], [], 0.0
        for path in sorted(PREDICTIONS.glob(f"{system}__*.jsonl")):
            for line in path.open():
                if not line.strip():
                    continue
                row = json.loads(line)
                if row.get("error"):
                    continue
                if row.get("latency_ms") is not None:
                    latencies.append(float(row["latency_ms"]))
                usage = row.get("usage") or {}
                tokens_seen.append(usage.get("output_tokens") or usage.get("completion_tokens") or 0)
                if usage.get("input_tokens"):
                    cost += usage["input_tokens"] * 0.042e-6
                elif usage.get("prompt_tokens"):
                    cost += usage["prompt_tokens"] * 0.10e-6 + usage.get("completion_tokens", 0) * 0.15e-6
        latencies.sort()
        mean_latency = sum(latencies) / len(latencies) if latencies else 0.0
        median = latencies[len(latencies) // 2] if latencies else 0.0
        p95 = latencies[int(0.95 * (len(latencies) - 1))] if latencies else 0.0
        tokens = sum(tokens_seen) / len(tokens_seen) if tokens_seen else 0.0
        cost_text = "local" if system == "nli" else f"\\${cost / len(latencies) * 1000:.3f}"
        lines.append(f"{SHORT.get(system, system)} & {median:.0f} & {mean_latency:.0f} & {p95:.0f} & {tokens:.1f} & {cost_text} \\\\")
    lines.append("\\bottomrule")
    lines.append("\\end{tabular}")
    lines.append("\\end{table}")
    lines.append("")

    lines.append("\\begin{table}[t]\\centering\\small")
    lines.append("\\caption{Error rate when the claim contains a number, compared with claims that do not. At pilot scale "
                 "(60 cases per dataset) numeric claims looked like the dominant failure feature; at 300 the gap narrows to a "
                 "few points and reverses sign in several cells, so we report it as weak evidence rather than a finding.}")
    lines.append("\\label{tab:numeric}")
    lines.append("\\begin{tabular}{lrr}")
    lines.append("\\toprule")
    lines.append("System & Error, numeric claim & Error, no numeric claim \\\\")
    lines.append("\\midrule")
    for system in systems:
        rows = [r for r in failures if r["system"] == system and r["feature"] == "numeric_in_claim"]
        yes = [r for r in rows if r["value"] == "True"]
        no = [r for r in rows if r["value"] == "False"]
        if not yes:
            continue
        yes_rate = sum(float(r["error_rate"]) * int(r["n"]) for r in yes) / sum(int(r["n"]) for r in yes)
        if no:
            no_rate = sum(float(r["error_rate"]) * int(r["n"]) for r in no) / sum(int(r["n"]) for r in no)
            no_text = f"{no_rate:.3f}"
        else:
            no_text = "--"
        lines.append(f"{SHORT.get(system, system)} & {yes_rate:.3f} & {no_text} \\\\")
    lines.append("\\bottomrule")
    lines.append("\\end{tabular}")
    lines.append("\\end{table}")

    (RESULTS / "paper_tables.tex").write_text("\n".join(lines) + "\n")
    print(f"wrote {RESULTS / 'paper_tables.tex'}")


if __name__ == "__main__":
    main()
