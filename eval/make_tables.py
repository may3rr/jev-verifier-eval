"""Regenerate table.md from the frozen prediction logs and metric CSVs."""
from __future__ import annotations

import csv
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RESULTS = ROOT / "results"
UNIFIED = ROOT / "data" / "unified"

DATASET_ROWS = [
    ("FEVER", "fever", "Wikipedia fact verification", "SUPPORTS / REFUTES / NEI", "FEVER score; any complete gold evidence set"),
    ("SciFact", "scifact", "Scientific abstracts with rationales", "SUPPORTS / REFUTES / NEI", "Label accuracy; rationale sentence F1"),
    ("HoVer", "hover", "Many-hop Wikipedia verification", "SUPPORTS / REFUTES", "All annotated hops must be recovered"),
    ("VitaminC", "vitaminc", "Contrastive minimal edits", "SUPPORTS / REFUTES / NEI", "Accuracy; paired consistency"),
    ("Climate-FEVER", "climate_fever", "Climate claims against report evidence", "SUPPORTS / REFUTES / NEI", "FEVER-style score; evidence F1"),
]

SYSTEM_LABEL = {
    "jev": "JEV typed `noul` questions",
    "nli": "DeBERTa-v3-large NLI (local)",
    "qwen-direct-compact": "Qwen direct, compact prompt",
    "qwen-direct-expanded": "Qwen direct, expanded prompt",
    "qwen-cot-compact": "Qwen reason-then-answer, compact prompt",
    "qwen-cot-expanded": "Qwen reason-then-answer, expanded prompt",
}

HIGHLIGHT = {
    "jev": "Typed Boolean probabilities; no free-form parsing; lowest protocol-failure rate",
    "nli": "Local MPS inference; pretrained NLI, no task-specific tuning",
    "qwen-direct-compact": "Cheapest condition: one output token per case",
    "qwen-direct-expanded": "Controls for prompt detail without reasoning tokens",
    "qwen-cot-compact": "Reasoning budget with short instructions",
    "qwen-cot-expanded": "Highest reasoning budget; out-of-label-space abstentions on binary HoVer",
}


def pooled_stats(system: str) -> tuple[float, float, float]:
    """Pooled latency/tokens over every logged request of a system."""
    predictions = ROOT / "results" / "predictions"
    latencies, tokens = [], []
    for path in sorted(predictions.glob(f"{system}__*.jsonl")):
        for line in path.open():
            if not line.strip():
                continue
            row = json.loads(line)
            if row.get("latency_ms") is not None and not row.get("error"):
                latencies.append(float(row["latency_ms"]))
            usage = row.get("usage") or {}
            tokens.append(usage.get("output_tokens") or usage.get("completion_tokens") or 0)
    latencies.sort()
    mean_latency = sum(latencies) / len(latencies) if latencies else 0.0
    p95 = latencies[int(0.95 * (len(latencies) - 1))] if latencies else 0.0
    return mean_latency, p95, (sum(tokens) / len(tokens) if tokens else 0.0)


def fmt(value: str | None, digits: int = 3) -> str:
    if value in (None, "", "None"):
        return "pending"
    number = float(value)
    return f"{number:.{digits}f}"


def main() -> None:
    summary = list(csv.DictReader((RESULTS / "summary.csv").open()))
    per_class = list(csv.DictReader((RESULTS / "per_class.csv").open()))
    failures = list(csv.DictReader((RESULTS / "failure_features.csv").open()))
    manifest = json.loads((UNIFIED / "manifest.json").read_text()) if (UNIFIED / "manifest.json").exists() else []
    counts = {}
    for path in sorted(UNIFIED.glob("*.jsonl")):
        counts[path.stem] = sum(1 for line in path.open() if line.strip())

    runs = sorted({(row["system"], row["model"]) for row in summary})
    lines: list[str] = []
    lines.append("# Claim-evidence benchmark table")
    lines.append("")
    lines.append(
        "Single source of truth for the claim-evidence evaluation. Every number below is "
        "generated by `eval/make_tables.py` from `results/summary.csv`, which in turn comes "
        "from the raw request logs in `results/predictions/`. A metric marked `pending` has "
        "not been measured; it is not a zero."
    )
    lines.append("")
    lines.append("## 1. Dataset registry")
    lines.append("")
    lines.append("| Dataset | Domain / challenge | Labels | Unified examples | Primary metric | Evidence constraint |")
    lines.append("|---|---|---|---:|---|---|")
    for display, key, domain, labels, metric in DATASET_ROWS:
        lines.append(f"| {display} | {domain} | {labels} | {counts.get(key, 0):,} | {metric} | Frozen local copy |")
    lines.append("")
    lines.append(
        "FEVER, SciFact and HoVer use the labelled development split; VitaminC uses its dev and "
        "test splits; Climate-FEVER ships a single annotated split. FEVER and Climate-FEVER "
        "NEI/insufficient cases are paired with distractor evidence rather than an empty evidence "
        "list, and HoVer is binary, so its prompt exposes only the two labels it actually has."
    )
    lines.append("")

    lines.append("## 2. Accuracy and macro-F1 by model and dataset")
    lines.append("")
    lines.append("| System | Model | Dataset | n | Accuracy | 95% CI | Macro-F1 | Brier | Parse failures | Highlight |")
    lines.append("|---|---|---|---:|---:|---|---:|---:|---:|---|")
    for row in summary:
        if row["brier"] == "None":
            brier = "n/a"
        else:
            brier = fmt(row["brier"])
        lines.append(
            f"| {SYSTEM_LABEL.get(row['system'], row['system'])} | `{row['model']}` | {row['dataset']} | "
            f"{row['n_scored']} | {fmt(row['accuracy'])} | "
            f"{fmt(row['accuracy_ci_low'])}-{fmt(row['accuracy_ci_high'])} | {fmt(row['macro_f1'])} | {brier} | "
            f"{row['parse_failures']} | {HIGHLIGHT.get(row['system'], '')} |"
        )
    lines.append("")

    lines.append("## 3. Per-class performance")
    lines.append("")
    lines.append("| System | Dataset | Label | Precision | Recall | F1 | Gold support | Predicted |")
    lines.append("|---|---|---|---:|---:|---:|---:|---:|")
    for row in per_class:
        lines.append(
            f"| {SYSTEM_LABEL.get(row['system'], row['system'])} | {row['dataset']} | {row['label']} | "
            f"{fmt(row['precision'])} | {fmt(row['recall'])} | {fmt(row['f1'])} | {row['support']} | {row['predicted']} |"
        )
    lines.append("")

    lines.append("## 4. Efficiency and protocol reliability")
    lines.append("")
    lines.append("| System | Model | Mean latency (ms) | p95 latency (ms) | Mean output tokens | Highlight |")
    lines.append("|---|---|---:|---:|---:|---|")
    for system, model in runs:
        mean_latency, p95, tokens = pooled_stats(system)
        lines.append(
            f"| {SYSTEM_LABEL.get(system, system)} | `{model}` | {mean_latency:.0f} | {p95:.0f} | {tokens:.1f} | "
            f"{HIGHLIGHT.get(system, '')} |"
        )
    lines.append("")

    lines.append("## 5. Failure features")
    lines.append("")
    lines.append("| System | Dataset | Feature | Value | n | Error rate |")
    lines.append("|---|---|---|---|---:|---:|")
    interesting = [row for row in failures if row["feature"] in
                   {"long_evidence", "many_records", "negation_in_claim", "scope_word_in_claim",
                    "modality_in_claim", "numeric_in_claim", "causal_in_claim"}]
    interesting.sort(key=lambda row: -float(row["error_rate"]))
    for row in interesting[:24]:
        lines.append(
            f"| {SYSTEM_LABEL.get(row['system'], row['system'])} | {row['dataset']} | {row['feature']} | "
            f"{row['value']} | {row['n']} | {float(row['error_rate']):.3f} |"
        )
    lines.append("")

    lines.append("## 6. Result entry rules")
    lines.append("")
    lines.append("1. Fill cells only from a frozen run manifest: dataset hash, model revision, prompt hash, seed, and API date.")
    lines.append("2. The inference unit is the claim/evidence bundle; report clustered bootstrap intervals for differences.")
    lines.append("3. Report protocol failures separately from wrong answers; a rate-limited or unparsable request is not a wrong prediction.")
    lines.append("4. Thresholds, if any, are selected on the development split and frozen before the test split is scored.")
    lines.append("")

    if manifest:
        lines.append("## 7. Build manifest")
        lines.append("")
        lines.append("| Dataset | Unified records | Source path |")
        lines.append("|---|---:|---|")
        for entry in manifest:
            lines.append(f"| {entry['dataset']} | {entry['records']:,} | `{entry['path']}` |")
        lines.append("")

    (ROOT / "table.md").write_text("\n".join(lines))
    print(f"wrote {ROOT / 'table.md'} with {len(summary)} summary rows")


if __name__ == "__main__":
    main()
